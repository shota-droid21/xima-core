"""labels.json の item を指す鍵（`file_id`）の作り方（#409）。

**鍵は item 自身の相対パスだけから決める。**他の画像が在るか、走査の順番が
どうだったかで変わってはならない。変われば、次に一覧を作り直したときに
既存の item と突き合わせられず、**付けたラベルを失う。**

以前は `Path(rel_path).stem`（ファイル名の語幹）だった。`a/photo.png` と
`b/photo.png` が同じ `photo` になり、`make_label_list` の突き合わせで後から
来た方が前を上書きしていた。**2 枚が 1 件に畳まれ、先に付けたラベルが別の
画像へ移っていた**（#380 で再現）。

## 採った案と、採らなかった案

| 案 | 同名衝突 | 移動・改名 | 読めるか |
| --- | --- | --- | --- |
| **相対パス（これ）** | 解消する | 追従しない | **読める** |
| 相対パスのハッシュ | 解消する | 追従しない | 読めない |
| 内容のハッシュ | 解消する | 追従する | 読めない |

**内容のハッシュは採らない。**「同じ内容の別ファイルを同一視するか」という
別の判断を含む。#380 が未決としているので、ここでは決めない。

**ハッシュにしない。**鍵が不透明になると、障害の報告を受けても
「どの画像の話か」を `labels.json` から読み取れない。相対パスはそのまま読める。
鍵の長さは問題にならない（サムネイルの置き場は sha1 を通すため）。

**移動・改名に追従しないのは承知のうえ。**追従させるには内容を見るしかなく、
それは #380 の範囲である。移動したときは一覧を作り直せば新しい鍵で記録される。

## 正規化

区切りは `/` に寄せる。`os.path.relpath` は Windows で `\\` を返すため、
**同じ画像が OS によって別の鍵になる**のを防ぐ。先頭の `./` も落とす。
"""

from __future__ import annotations

from pathlib import Path


def file_id_for_path(rel_path: str | Path | None) -> str:
    """item の相対パスから `file_id` を作る。決められないときは空文字。

    呼ぶ側は `labels.json` に記録されている `path` をそのまま渡してよい。
    """
    raw = str(rel_path or "").strip()
    if not raw:
        return ""

    # `..` は畳まない。畳むと別の場所を指す 2 つが同じ鍵になりうる。
    parts = [p for p in raw.replace("\\", "/").split("/") if p not in ("", ".")]
    return "/".join(parts)
